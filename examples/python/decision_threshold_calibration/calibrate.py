"""Turn Decisions-style probabilities into actions: reliability check, cost-based approve/review/deny band,
score-level thresholds and refusal routing.

Author: Sandeep Belgavi. Offline companion to "From Probabilities to Actions With the Decisions API"
(aicassindra.com). Nothing here calls a provider: the labelled fixture is synthetic and generated by
make_fixture() from a fixed seed, and parse_answers() reads answers shaped like the documented
response object (predicate, choice, score, refusal), not a recorded API response.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def make_fixture(n=200, seed=7):
    """Synthetic labelled predicates for 'is the duplicate charge supported by the evidence?'.

    Each item has a true chance q of being a real duplicate, and its label is drawn with that chance.
    The simulated model is overconfident: it reports sigmoid(2 * logit(q)), which pushes q towards
    0 and 1. That is the case a reliability check must catch before thresholds are trusted.
    """
    import math
    state = seed
    def rnd():
        nonlocal state
        state = (state * 1103515245 + 12345) % 2147483648
        return (state + 0.5) / 2147483648
    items = []
    for i in range(n):
        u = rnd() ** 3                                   # most cases are clear-cut
        q = 0.03 + 0.94 * (u if rnd() < 0.45 else 1 - u)
        label = rnd() < q
        logit = math.log(q / (1 - q))
        prob = 1 / (1 + math.exp(-2 * logit))
        items.append({"id": "T-%03d" % (i + 1), "probability": round(prob, 3), "label": label})
    return items


def reliability_table(items, bins=5):
    """Per probability bin: count, mean predicted probability, observed rate of true labels."""
    rows = []
    for b in range(bins):
        lo, hi = b / bins, (b + 1) / bins
        sel = [x for x in items if lo <= x["probability"] < hi or (b == bins - 1 and x["probability"] == 1.0)]
        if sel:
            rows.append({"bin": "%.1f-%.1f" % (lo, hi), "count": len(sel),
                         "mean_predicted": round(sum(x["probability"] for x in sel) / len(sel), 3),
                         "observed": round(sum(x["label"] for x in sel) / len(sel), 3)})
    return rows


def band_cost(items, low, high, cost):
    """Approve at or above `high`, deny at or below `low`, send the rest to a person."""
    total = {"wrong_approve": 0, "wrong_deny": 0, "reviewed": 0}
    for x in items:
        p = x["probability"]
        if p >= high:
            total["wrong_approve"] += not x["label"]
        elif p <= low:
            total["wrong_deny"] += x["label"]
        else:
            total["reviewed"] += 1
    total["cost"] = (total["wrong_approve"] * cost["wrong_approve"] + total["wrong_deny"] * cost["wrong_deny"]
                     + total["reviewed"] * cost["review"])
    return total


def choose_band(items, cost, step=0.05):
    """Grid search for the cheapest (low, high) band on the labelled sample."""
    grid = [round(i * step, 2) for i in range(int(1 / step) + 1)]
    best = None
    for low in grid:
        for high in grid:
            if high <= low:
                continue
            c = band_cost(items, low, high, cost)
            key = (c["cost"], high - low)
            if best is None or key < best[0]:
                best = (key, low, high, c)
    return {"low": best[1], "high": best[2], **best[3]}


def at_least(score_answer, level_value):
    """P(level index >= level_value) from a score answer's probabilities. Do not round answer['score']."""
    return round(sum(p["probability"] for p in score_answer["probabilities"] if p["value"] >= level_value), 6)


def parse_answers(decision, band, severity_cut=2):
    """Map one decision object to actions. A refusal never becomes an approval or a denial."""
    actions = {}
    for a in decision["answers"]:
        name = a.get("name")
        if a["type"] == "refusal":
            actions[name] = "review: refused"
        elif a["type"] == "predicate":
            p = a["probability"]
            actions[name] = "approve" if p >= band["high"] else "deny" if p <= band["low"] else "review"
        elif a["type"] == "choice":
            chosen = next(x["probability"] for x in a["probabilities"] if x["value"] == a["choice"])
            actions[name] = "route:%s" % a["choice"] if chosen >= 0.8 else "review: low probability"
        elif a["type"] == "score":
            actions[name] = "page on-call" if at_least(a, severity_cut) >= 0.5 else "queue"
    return actions


COST = {"wrong_approve": 40, "wrong_deny": 25, "review": 3}


def main():
    items = make_fixture()
    print("items", len(items), "true", sum(x["label"] for x in items))
    for row in reliability_table(items):
        print("bin %(bin)s count %(count)3d predicted %(mean_predicted).3f observed %(observed).3f" % row)
    naive = band_cost(items, 0.5, 0.5 + 1e-9, COST)
    print("naive 0.5 cut:", naive)
    band = choose_band(items, COST)
    print("chosen band:", band)
    fit, holdout = items[:100], items[100:]
    fitted = choose_band(fit, COST)
    print("band fitted on items 1-100:", fitted)
    print("same band on items 101-200:", band_cost(holdout, fitted["low"], fitted["high"], COST))
    print("naive 0.5 cut on items 101-200:", band_cost(holdout, 0.5, 0.5 + 1e-9, COST))
    decision = json.loads((HERE / "fixtures" / "decision_shaped.json").read_text(encoding="utf-8"))
    print("actions:", parse_answers(decision, band))


if __name__ == "__main__":
    main()
